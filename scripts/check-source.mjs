import {readFile,stat} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const config=JSON.parse(await readFile(resolve(root,'.openai/hosting.json'),'utf8'));
if(!config.project_id||config.d1!=='DB'||!config.capabilities?.includes('mcp')||config.static)throw new Error('Worker DB/MCP manifest is incomplete.');
for(const file of ['index.html','app.js','cloud.mjs','story-model.mjs','style.css','panel-1.jpg','panel-2.jpg','panel-3.jpg','comic.jpg'])if(!(await stat(resolve(root,'public',file))).isFile())throw new Error('Missing UI asset: '+file);
const model=await import('../public/story-model.mjs');
for(const key of ['DEMO','copy','esc','safeImage','normalize'])if(!(key in model))throw new Error('Missing browser/server model export: '+key);
console.log('Worker manifest, UI assets and shared model exports verified.');
